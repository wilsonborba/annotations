"""Write the Spectrum 2 workflow icons that Annotations uses as Dart path data.

Source: the npm package @adobe/spectrum-css-workflow-icons (Apache-2.0),
folder dist/assets/svg. The path data is copied without change; only the
file format changes (SVG to a Dart constant).

Usage: python3 -I scripts/spectrum_icons.py <svg folder> <package version>
"""

