/// A Reports card address derived from a link or an API response.
///
/// This accepts only URLs that the current Reports source emits. Persisted
/// Notes use the explicit tuple fields, never this URL.
final class ReportsCardReference {
  const ReportsCardReference({
    required this.project,
    required this.report,
    required this.dataset,
  });

  final String project;
  final String report;
  final String dataset;

  static final _slugPattern = RegExp(r'^[a-z][a-z0-9_-]{1,47}$');

  static bool isValidSlug(String value) => _slugPattern.hasMatch(value);

  static ReportsCardReference? fromFields({
    required String project,
    required String report,
    required String dataset,
  }) {
    if (![project, report, dataset].every(isValidSlug)) return null;
    return ReportsCardReference(
      project: project,
      report: report,
      dataset: dataset,
    );
  }

  /// Parses a Reports menu/embed URL or the relative owner embed URL. Query
  /// parameters are discarded because they can contain sensitive filters.
  static ReportsCardReference? tryParse(String value) {
    final uri = Uri.tryParse(value.trim());
    if (uri == null || uri.hasFragment || uri.userInfo.isNotEmpty) return null;

    List<String> parts;
    if (uri.hasScheme || uri.hasAuthority) {
      final rawAuthority = RegExp(
        r'^https://([^/?#]+)',
      ).firstMatch(value.trim())?.group(1);
      if (uri.scheme != 'https' ||
          uri.host.toLowerCase() != 'reports.asodya.com' ||
          rawAuthority != 'reports.asodya.com') {
        return null;
      }
      parts = uri.pathSegments;
      if (parts.length != 5 ||
          parts[0] != 'v1' ||
          (parts[1] != 'menu' && parts[1] != 'embed')) {
        return null;
      }
      parts = parts.sublist(2);
    } else {
      if (!uri.path.startsWith('/') ||
          uri.pathSegments.length != 7 ||
          uri.pathSegments[0] != 'projects' ||
          uri.pathSegments[2] != 'showcase' ||
          uri.pathSegments[4] != 'cards' ||
          uri.pathSegments[6] != 'embed') {
        return null;
      }
      parts = [uri.pathSegments[1], uri.pathSegments[3], uri.pathSegments[5]];
    }

    if (!parts.every(isValidSlug)) {
      return null;
    }
    return ReportsCardReference(
      project: parts[0],
      report: parts[1],
      dataset: parts[2],
    );
  }

  /// The canonical source URL generated by Reports for an individual card.
  String get sourceUrl =>
      'https://reports.asodya.com/v1/menu/${Uri.encodeComponent(project)}/${Uri.encodeComponent(report)}/${Uri.encodeComponent(dataset)}';

  String get reportViewPath =>
      '/projects/${Uri.encodeComponent(project)}/reports/${Uri.encodeComponent(report)}';

  String get datasetPath =>
      '$reportViewPath/datasets/${Uri.encodeComponent(dataset)}';

  String get viewerEmbedPath =>
      '$reportViewPath/cards/${Uri.encodeComponent(dataset)}/embed';

  String get snapshotsPath =>
      '$reportViewPath/cards/${Uri.encodeComponent(dataset)}/snapshots';

  String snapshotPath(String snapshotId) =>
      '$snapshotsPath/${Uri.encodeComponent(snapshotId)}';

  @override
  bool operator ==(Object other) =>
      other is ReportsCardReference &&
      project == other.project &&
      report == other.report &&
      dataset == other.dataset;

  @override
  int get hashCode => Object.hash(project, report, dataset);
}
