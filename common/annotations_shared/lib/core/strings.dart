String translate(
  String key,
  String locale, [
  Map<String, String> args = const {},
]) {
  final index = locale == 'pt-BR'
      ? 1
      : locale == 'th'
      ? 2
      : 0;
  var value = (strings[key] ?? landingStrings[key])?[index] ?? key;
  for (final entry in args.entries) {
    value = value.replaceAll('{${entry.key}}', entry.value);
  }
  return value;
}

